namespace RQI.POC.AutoGen
{
    public static partial class Utilities
    {
        public static class AutoDALFileSystem
        {
            public static void DeletaAllAutoGeneratedFiles(string targetFolder)
            {
                // Check if folder exists.  If not return.
                if (!System.IO.Directory.Exists(targetFolder)) return;

                var autoGenFiles = System.IO.Directory.GetFiles(targetFolder, $"*.{Utilities.AutogGenFileExtension}", System.IO.SearchOption.AllDirectories);
                foreach (var file in autoGenFiles)
                {
                    System.IO.File.Delete(file);
                }
            }

            public static void DeleteAllGeneratedFiles()
            {
                DeletaAllAutoGeneratedFiles(Utilities.Config.AppSettings.Settings["AutoGenTablesFolder"].Value);
                DeletaAllAutoGeneratedFiles(Utilities.Config.AppSettings.Settings["AutoGenViewsFolder"].Value);
                DeletaAllAutoGeneratedFiles(Utilities.Config.AppSettings.Settings["AutoGenSprocsFolder"].Value);
                DeletaAllAutoGeneratedFiles(Utilities.Config.AppSettings.Settings["AutoGenTypesFolder"].Value);
            }
        }
    }
}
